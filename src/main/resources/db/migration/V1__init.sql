-- HackerCode initial schema. Written in portable SQL that runs on both H2 (development) and PostgreSQL.

CREATE TABLE app_user (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                VARCHAR(320)  NOT NULL,
    password_hash        VARCHAR(255),
    display_name         VARCHAR(80)   NOT NULL,
    avatar_url           VARCHAR(1024),
    role                 VARCHAR(20)   NOT NULL,
    status               VARCHAR(20)   NOT NULL,
    email_verified       BOOLEAN       NOT NULL,
    google_subject       VARCHAR(255),
    onboarding_completed BOOLEAN       NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_user_email UNIQUE (email),
    CONSTRAINT uq_user_google UNIQUE (google_subject)
);

CREATE TABLE user_settings (
    user_id       BIGINT PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
    settings_json VARCHAR(20000) NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE auth_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    type       VARCHAR(30)  NOT NULL,
    token_hash VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_auth_token_hash UNIQUE (token_hash)
);
CREATE INDEX ix_auth_token_user ON auth_token (user_id, type);

CREATE TABLE user_session (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    session_key     VARCHAR(64)  NOT NULL,
    user_agent      VARCHAR(300),
    ip_hint         VARCHAR(64),
    remember_me     BOOLEAN      NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_user_session_key UNIQUE (session_key)
);
CREATE INDEX ix_user_session_user ON user_session (user_id);

-- Table layout required by Spring Security's JdbcTokenRepositoryImpl (persistent remember-me tokens)
CREATE TABLE persistent_logins (
    username  VARCHAR(320) NOT NULL,
    series    VARCHAR(64)  PRIMARY KEY,
    token     VARCHAR(64)  NOT NULL,
    last_used TIMESTAMP    NOT NULL
);

CREATE TABLE topic (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug     VARCHAR(120) NOT NULL,
    name     VARCHAR(255) NOT NULL,
    position INT          NOT NULL,
    CONSTRAINT uq_topic_slug UNIQUE (slug)
);

CREATE TABLE problem (
    id                 VARCHAR(16)   PRIMARY KEY,
    source_number      INT,
    position           INT           NOT NULL,
    slug               VARCHAR(120)  NOT NULL,
    title              VARCHAR(300)  NOT NULL,
    source_text        VARCHAR(1000),
    source_note        VARCHAR(1000),
    topic_id           BIGINT        NOT NULL REFERENCES topic (id),
    subsection         VARCHAR(300),
    subsection_position INT          NOT NULL,
    practice_urls      VARCHAR(2000),
    difficulty         VARCHAR(10),
    statement          VARCHAR(20000),
    constraints_text   VARCHAR(5000),
    examples_text      VARCHAR(10000),
    tests_json         VARCHAR(100000),
    provenance         VARCHAR(20)   NOT NULL,
    content_updated_by VARCHAR(320),
    archived           BOOLEAN       NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_problem_slug UNIQUE (slug),
    CONSTRAINT uq_problem_source_number UNIQUE (source_number)
);
CREATE INDEX ix_problem_topic ON problem (topic_id, position);
CREATE INDEX ix_problem_position ON problem (position);

CREATE TABLE problem_progress (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    problem_id     VARCHAR(16) NOT NULL REFERENCES problem (id) ON DELETE CASCADE,
    status         VARCHAR(20) NOT NULL,
    bookmarked     BOOLEAN     NOT NULL,
    notes          VARCHAR(20000),
    last_viewed_at TIMESTAMP WITH TIME ZONE,
    solved_at      TIMESTAMP WITH TIME ZONE,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_progress UNIQUE (user_id, problem_id)
);
CREATE INDEX ix_progress_user ON problem_progress (user_id, status);

CREATE TABLE code_draft (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    draft_key  VARCHAR(40)  NOT NULL,
    language   VARCHAR(20)  NOT NULL,
    code       VARCHAR(200000) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_code_draft UNIQUE (user_id, draft_key, language)
);

CREATE TABLE execution_run (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    problem_id     VARCHAR(16)  REFERENCES problem (id) ON DELETE SET NULL,
    language       VARCHAR(20)  NOT NULL,
    kind           VARCHAR(10)  NOT NULL,
    status         VARCHAR(30)  NOT NULL,
    provider       VARCHAR(20)  NOT NULL,
    stdout         VARCHAR(20000),
    stderr         VARCHAR(20000),
    compile_output VARCHAR(20000),
    exit_code      INT,
    time_ms        BIGINT,
    memory_kb      BIGINT,
    tests_passed   INT,
    tests_total    INT,
    code           VARCHAR(200000),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_execution_user ON execution_run (user_id, created_at);

CREATE TABLE code_review (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    problem_id   VARCHAR(16)   REFERENCES problem (id) ON DELETE SET NULL,
    language     VARCHAR(20)   NOT NULL,
    provider     VARCHAR(30)   NOT NULL,
    model        VARCHAR(100),
    ai_generated BOOLEAN       NOT NULL,
    summary      VARCHAR(4000),
    score        INT,
    finding_count INT          NOT NULL,
    result_json  VARCHAR(200000) NOT NULL,
    code         VARCHAR(200000) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_review_user ON code_review (user_id, created_at);

CREATE TABLE activity_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    type        VARCHAR(30)  NOT NULL,
    problem_id  VARCHAR(16),
    language    VARCHAR(20),
    occurred_on DATE         NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_activity_user ON activity_event (user_id, created_at);

CREATE TABLE notification (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    title      VARCHAR(200)  NOT NULL,
    body       VARCHAR(2000),
    read_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_notification_user ON notification (user_id, created_at);

CREATE TABLE audit_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT,
    actor_email VARCHAR(320),
    action      VARCHAR(60)  NOT NULL,
    target_type VARCHAR(40),
    target_id   VARCHAR(80),
    detail      VARCHAR(2000),
    ip_hint     VARCHAR(64),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_audit_created ON audit_event (created_at);

CREATE TABLE platform_setting (
    setting_key VARCHAR(80)   PRIMARY KEY,
    setting_value VARCHAR(2000) NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by  VARCHAR(320)
);
